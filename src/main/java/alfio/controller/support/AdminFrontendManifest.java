package alfio.controller.support;

import org.springframework.core.io.ClassPathResource;
import org.springframework.stereotype.Component;
import tools.jackson.core.type.TypeReference;
import tools.jackson.databind.ObjectMapper;

import java.io.IOException;
import java.util.List;
import java.util.Map;
import java.util.Optional;

/**
 * The files of the admin frontend (frontend/admin) built by Vite, read from its manifest. In development the manifest
 * doesn't exist: the pages load the sources from the Vite dev server instead.
 */
@Component
public class AdminFrontendManifest {

    public record ManifestEntry(List<String> css, String file) {
    }

    private static final String MAIN_ENTRY = "src/main.ts";
    private static final String LOGIN_STYLES_ENTRY = "src/login.css";
    /**
     * Polyfills for the oldest supported browsers, generated by @vitejs/plugin-legacy (see frontend/admin/vite.config.js)
     */
    private static final String POLYFILLS_ENTRY = "vite/legacy-polyfills";

    private final Map<String, ManifestEntry> manifest;

    public AdminFrontendManifest(ObjectMapper objectMapper) throws IOException {
        var cpr = new ClassPathResource("/resources/alfio-admin-frontend/.vite/manifest.json");
        if (cpr.exists()) {
            try (var descriptor = cpr.getInputStream()) {
                this.manifest = objectMapper.readValue(descriptor, new TypeReference<Map<String, ManifestEntry>>() {});
            }
        } else {
            this.manifest = Map.of();
        }
    }

    public Optional<ManifestEntry> mainEntry() {
        return Optional.ofNullable(manifest.get(MAIN_ENTRY));
    }

    public Optional<ManifestEntry> polyfills() {
        return Optional.ofNullable(manifest.get(POLYFILLS_ENTRY));
    }

    /**
     * The stylesheet of the login page, a CSS entry of the build
     */
    public Optional<String> loginStylesheet() {
        return Optional.ofNullable(manifest.get(LOGIN_STYLES_ENTRY)).map(ManifestEntry::file);
    }
}
